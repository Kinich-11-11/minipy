 const cat=(v)=>{ v=String(v);
   if (/^[A-Z][A-Z0-9_]{1,}$/.test(v)) return 'opcode-dispatch:'+v;
   if (['+','-','*','/','//','%','**','==','!=','<','>','<=','>=','and','or','not','is','isnot','in','notin'].includes(v)) return 'binop:'+v;
   if (v.indexOf('|')>=0) return 'name-lookup';
   if (['B0','B1','Z','S','N','L','T','D','F','C','O'].includes(v)) return 'tag:'+v;
   if (/^-?[0-9.]+$/.test(v)) return 'number';
   return 'other:'+JSON.stringify(v.slice(0,14)); };
