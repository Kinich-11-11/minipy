 for(const n of ['mode','ticket','stopreq','running']) sv(n).value=0;
 sv('ticket').value=1; sv('running').value=1; sv('speed').value=1;
 rt.startHats('event_whenbroadcastreceived',{BROADCAST_OPTION:'RUN'});
 for(let i=0;i<300000;i++){ rt._step(); if(i>4 && String(sv('running').value)==='0') break; }
 const show=(title,obj,tot)=>{ realLog(title+' total='+tot);
   for (const [k,c] of Object.entries(obj).sort((a,b)=>b[1]-a[1]).slice(0,12)) realLog('   '+String(c).padStart(9)+'  '+(100*c/tot).toFixed(1)+'%  '+k); };
 show('operator_equals', stat.eq, stat.total.eq);
 show('data_variable', stat.vars, stat.total.vars);
