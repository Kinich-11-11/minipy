const fs = require("fs");
const lines = [];
lines.push("// PZ74（临时调试）：eval 里哪些 fail 会因为名字找不到而触发？");
lines.push("patch('PZ74 eval namefail probes', () => {");
lines.push("  const ev = reach(defIdOf('eval %s %s'));");
lines.push("  let n = 0;");
lines.push("  const info = [];");
lines.push("  for (const id of ev) {");
lines.push("    const b = BL()[id];");
lines.push("    if (b.opcode !== 'procedures_call' || !b.mutation || b.mutation.proccode !== 'fail %s') continue;");
lines.push("    let hit = false;");
lines.push("    const walk = (x, d) => {");
lines.push("      if (!x || d > 12 || typeof x !== 'string' || hit) return;");
lines.push("      const q = BL()[x];");
lines.push("      if (!q) return;");
lines.push("      if (JSON.stringify(q).indexOf('is not defined') >= 0) { hit = true; return; }");
lines.push("      for (const v of Object.values(q.inputs || {})) if (Array.isArray(v) && typeof v[1] === 'string') walk(v[1], d + 1);");
lines.push("      walk(q.next, d + 1);");
lines.push("    };");
lines.push("    for (const v of Object.values(b.inputs || {})) if (Array.isArray(v) && typeof v[1] === 'string') walk(v[1], 0);");
lines.push("    if (!hit) continue;");
lines.push("    n++;");
lines.push("    info.push('#' + n + '=' + id);");
lines.push("    try { insertBeforeStmt(id, [FAIL(txt('PZ74 #' + n))]); } catch (e) { info.push('(skip)'); }");
lines.push("  }");
lines.push("  console.log('[PZ74] probed ' + n + ' sites: ' + info.join(' '));");
lines.push("});");
fs.writeFileSync("_work/v41/pz74.txt", lines.join("\n") + "\n");
console.log("wrote pz74.txt");