const fs = require('fs');
const p = '_work/v41/p291.txt';
let s = fs.readFileSync(p, 'utf8');
const helper = [
  "  const have = new Set(Object.values(T(IT).lists).map((x) => x[0]));",
  "  for (const l of ['ErrV', 'ErrT']) {",
  "    if (have.has(l)) throw new Error('[P291] list taken: ' + l);",
  "    B.addList(IT, l, []);",
  "  }",
  "  const hasText = (v, needle, d) => {",
  "    if (!v || d > 20) return false;",
  "    if (Array.isArray(v)) {",
  "      if ((v[0] === 10 || v[0] === 4) && typeof v[1] === 'string') return v[1].indexOf(needle) >= 0;",
  "      return v.some((x) => hasText(x, needle, d + 1));",
  "    }",
  "    return false;",
  "  };",
  "  const deepText = (id, needle, d) => {",
  "    if (!id || d > 25 || typeof id !== 'string') return false;",
  "    const b = BL()[id];",
  "    if (!b) return false;",
  "    if (b.opcode === 'text' && String(b.fields.TEXT[0]).indexOf(needle) >= 0) return true;",
  "    if (Object.values(b.inputs || {}).some((v) => hasText(v, needle, 0))) return true;",
  "    return deepText(b.next, needle, d + 1);",
  "  };",
  "  const hostIf = (fromId) => {",
  "    let cur = fromId;",
  "    for (let i = 0; i < 12 && cur; i++) {",
  "      const q = BL()[cur];",
  "      if ((q.opcode === 'control_if' || q.opcode === 'control_if_else') && q.inputs.CONDITION) return cur;",
  "      cur = q.parent;",
  "    }",
  "    return null;",
  "  };",
  "  // 内部 fail 清空 ErrV/ErrT（保证不会被上一次 raise 的实例污染）",
  "  insertBeforeStmt(BL()[defIdOf('fail %s')].next, [clearL('ErrV'), clearL('ErrT')]);",
  "  // raise 分支记录被 raise 的实例",
  "  {",
  "    const ids2 = new Set([...allIds(), ...Object.keys(T(IT).blocks)]);",
  "    let re = null;",
  "    for (const id of ids2) {",
  "      const b = BL()[id];",
  "      if (!b || b.opcode !== 'procedures_call' || !b.mutation || b.mutation.proccode !== 'fail %s') continue;",
  "      if (!deepText(id, 'No active exception to re-raise', 0)) continue;",
  "      re = id; break;",
  "    }",
  "    if (!re) throw new Error('[P291] re-raise site not found');",
  "    const h = hostIf(re);",
  "    if (!h) throw new Error('[P291] re-raise host not found');",
  "    insertBeforeStmt(h, [",
  "      IF(EQ(VAR('evtype'), txt('O')), [clearL('ErrV'), clearL('ErrT'), addTo('ErrV', VAR('ev')), addTo('ErrT', VAR('evtype'))])",
  "    ]);",
  "  }",
  ""
].join('\n');
